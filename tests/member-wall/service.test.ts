test("unbalanced groups preserve vacancies, filter changed gender and credit only actually assigned seats",async()=>{
  const id="group-"+randomUUID().slice(0,8),s=emptyActivity();
  s.participants=Array.from({length:34},(_,i)=>({...newParticipant(),name:"分区",gender:i<30?"male" as const:"female" as const,profileComplete:true,ready:true}));
  await db.query("INSERT INTO dl_activities(id,state) VALUES($1,$2)",[id,JSON.stringify(s)]);
  for(const p of s.participants)await wallConsent(id,{role:"participant",actor:p.id},{allow:true,nickname:"分区",expectedVersion:0,consentVersion:WALL_CONSENT_VERSION});
  const lease=await wallClaim(id,op,{owner:randomUUID(),capacity:24});
  assert.equal(lease.snapshot.cards.length,16);assert.equal(lease.snapshot.cards.filter(c=>c.gender==="male").length,12);
  assert.ok(lease.snapshot.cards.every(c=>c.gender===(c.slot%6<3?"male":"female")));
  const ids=lease.snapshot.cards.map(c=>c.id);
  const male=lease.snapshot.cards.find(c=>c.gender==="male")!;
  const actor=(await db.query('SELECT participant_id FROM dl_member_wall_consents WHERE public_id=$1',[male.id])).rows[0].participant_id;
  const saved=(await db.query('SELECT state FROM dl_activities WHERE id=$1',[id])).rows[0].state;saved.participants.find((p:{id:string})=>p.id===actor).gender="female";
  await db.query('UPDATE dl_activities SET state=$2 WHERE id=$1',[id,JSON.stringify(saved)]);
  const filtered=await wallSnapshot(id);assert.equal(filtered.cards.length,15);assert.equal(filtered.cards.some(c=>c.id===male.id),false);
  await db.query("UPDATE dl_member_wall_sessions SET heartbeat_at=now()-interval '5 seconds' WHERE activity_id=$1",[id]);
  const heartbeat=await wallScreenCommand(id,"heartbeat",{token:lease.token,sequence:1,batch:lease.snapshot.batch,elapsedMs:5000});
  assert.equal(heartbeat.cards.length,15);
  const exposures=(await db.query('SELECT public_id FROM dl_member_wall_exposure WHERE activity_id=$1',[id])).rows;
  assert.equal(exposures.length,15);assert.ok(exposures.every(e=>ids.includes(e.public_id)&&e.public_id!==male.id));
  await db.query("UPDATE dl_member_wall_sessions SET started_at=now()-interval '42 seconds',rotated_at=now()-interval '42 seconds' WHERE activity_id=$1",[id]);
  const next=await wallScreenCommand(id,"rotate",{token:lease.token,batch:heartbeat.batch,capacity:24});
  assert.equal(next.cards.length,17);assert.equal(next.cards.filter(c=>c.gender==="female").length,5);assert.ok(next.cards.every(c=>c.gender===(c.slot%6<3?"male":"female")));
});
