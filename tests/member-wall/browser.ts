import { chromium, expect } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
import { randomBytes,createHash,randomUUID } from 'node:crypto';
import { Pool } from 'pg';
import assert from 'node:assert/strict';
async function main() {
  const work=readFileSync('/tmp/destinylab-wall-work','utf8').trim();process.loadEnvFile(work+'/secrets/test.env');
  const f=JSON.parse(readFileSync(work+'/secrets/fixture.json','utf8')),origin='http://127.0.0.1:3241';
  const db=new Pool({connectionString:process.env.DATABASE_URL});
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const errors:string[]=[],checks:string[]=[];
  const route=(p:string)=>origin+'/api/member-wall/'+p+'?activity='+f.activity;
  try {
    const operator=await browser.newContext({viewport:{width:1920,height:1080}});
    const login=await operator.request.post(origin+'/api/live/login?activity='+f.activity,{headers:{Origin:origin},data:JSON.parse(readFileSync(work+'/secrets/operator.json','utf8'))});assert.equal(login.status(),200);
    const phone=await browser.newContext({viewport:{width:390,height:844}});
    const [name,value]=f.participantCookie.split('=');await phone.addCookies([{name,value,url:origin}]);
    const mobile=await phone.newPage();mobile.on('pageerror',e=>errors.push(e.message));
    await mobile.goto(origin+'/mobile/member-wall-consent?activity='+f.activity);
    await expect(mobile.getByRole('checkbox')).not.toBeChecked();
    await mobile.getByLabel('公开昵称').fill('春风拂过山间明月');
    await mobile.getByRole('button',{name:'看背面',exact:true}).click();
    await mobile.getByRole('checkbox').check();await mobile.getByRole('button',{name:'自愿开启卡牌展示'}).click();
    await expect(mobile.getByText('已开启；符合展示条件后，在下一换人周期加入。')).toBeVisible();
    await mobile.waitForTimeout(400);
    await mobile.screenshot({path:'docs/verification/member-wall/phone-consent.png',fullPage:true});checks.push('default-off, safe nickname fallback, front/back preview and real consent save');
    const wall=await operator.newPage();wall.on('pageerror',e=>errors.push(e.message));
    await wall.goto(origin+'/display/member-wall?activity='+f.activity);
    await wall.getByRole('button',{name:'启动主屏'}).click();await expect(wall.locator('[data-member]')).toHaveCount(24);
    const mirror=await operator.newPage();await mirror.goto(origin+'/display/member-wall?activity='+f.activity);
    await mirror.getByRole('button',{name:'启动主屏'}).click();await expect(mirror.locator('span[role="alert"]')).toContainText('已有主屏');
    checks.push('one operator main lease; second window read-only');
    const anon=await browser.newContext();
    assert.equal((await anon.request.get(route('admin'))).status(),401);
    assert.equal((await anon.request.post(route('claim'),{headers:{Origin:origin},data:{owner:crypto.randomUUID(),capacity:24}})).status(),401);
    assert.equal((await phone.request.post(route('consent'),{headers:{Origin:'https://invalid.example'},data:{}})).status(),403);
    assert.notEqual((await phone.request.get(origin+'/api/member-wall/me?activity=walltest')).status(),200);
    checks.push('anonymous writes, cross-activity cookie and cross-origin mutation denied');
    const snap=await (await anon.request.get(route('snapshot'))).json();
    assert.equal(JSON.stringify(snap).includes('PRIVATE'),false);assert.ok(snap.cards.every((c:{avatarUrl:string})=>c.avatarUrl.startsWith('/assets/avatars/')));
    await expect(wall.locator('[data-testid="member-wall"]')).toHaveAttribute('data-side','back',{timeout:14000});
    const victim=snap.cards[0].id;
    const g=(await db.query('SELECT participant_id,version,consent_version FROM dl_member_wall_consents WHERE public_id=$1',[victim])).rows[0];
    const token=randomBytes(32).toString('base64url');
    await db.query("INSERT INTO dl_sessions(token_hash,activity_id,role,actor,expires_at) VALUES($1,$2,'participant',$3,now()+interval '1 hour')",[createHash('sha256').update(token).digest('hex'),f.activity,g.participant_id]);
    const at=Date.now();
    const revoke=await anon.request.post(route('consent'),{headers:{Origin:origin,Cookie:`dl-participant-${f.activity}=${token}`},data:{allow:false,nickname:'',expectedVersion:g.version,consentVersion:g.consent_version}});
    assert.equal(revoke.status(),200);await expect(wall.locator(`[data-member="${victim}"]`)).toHaveCount(0,{timeout:5000});
    checks.push(`revocation during back face removed by SSE in ${Date.now()-at}ms`);
    // Keep the main page connected while taking only the read-only mirror offline.
    const offline=await browser.newContext({viewport:{width:1920,height:1080}});const screen=await offline.newPage();
    await screen.goto(origin+'/display/member-wall?activity='+f.activity);await expect(screen.locator('[data-member]').first()).toBeVisible({timeout:24000});
    await offline.setOffline(true);const disconnected=Date.now();
    await expect(screen.locator('[data-member]')).toHaveCount(0,{timeout:16000});
    await expect(screen.getByText('连接暂时中断',{exact:true})).toBeVisible();
    await screen.screenshot({path:'docs/verification/member-wall/offline-live.png'});
    checks.push(`offline visible data expired in ${Date.now()-disconnected}ms`);
    await offline.setOffline(false);await expect(screen.locator('[data-member]').first()).toBeVisible({timeout:24000});
    await screen.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'))});
    await expect(screen.locator('[data-member]')).toHaveCount(0);
    await screen.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:false});document.dispatchEvent(new Event('visibilitychange'))});
    await expect(screen.locator('[data-member]').first()).toBeVisible({timeout:24000});
    checks.push('offline reconnect and hidden/resume clear stale cards before fresh read');
    const admin=await operator.newPage();await admin.goto(origin+'/admin/member-wall?activity='+f.activity);
    await expect(admin.getByRole('button',{name:'保存展示设置'})).toBeEnabled();await admin.getByText('查看展示时长统计（不是观看人数）').click();
    await admin.screenshot({path:'docs/verification/member-wall/admin.png'});
    const stats=await (await operator.request.get(route('admin'))).json();assert.ok(stats.exposure.some((x:{seconds:number})=>x.seconds>0));
    checks.push('existing operator page loads config and persisted positive exposure statistics');
    await wall.setViewportSize({width:390,height:844});
    await expect(wall.getByText('请横屏或使用更大的显示区域',{exact:false})).toBeVisible();
    await expect(wall.locator('[data-member]')).toHaveCount(0);
    await wall.waitForTimeout(1000);
    const sum=async()=>Number((await db.query('SELECT sum(visible_ms) n FROM dl_member_wall_exposure WHERE activity_id=$1',[f.activity])).rows[0].n);
    const beforeHidden=await sum();await wall.waitForTimeout(6000);assert.equal(await sum(),beforeHidden);
    checks.push('unreadable viewport hides all cards and accrues zero exposure');
    await wall.setViewportSize({width:1920,height:1080});
    await expect(wall.locator('[data-member]').first()).toBeVisible({timeout:24000});
    const current=(await db.query('SELECT state FROM dl_activities WHERE id=$1',[f.activity])).rows[0].state;
    current.epoch=randomUUID();current.revision=0;
    await db.query('UPDATE dl_activities SET state=$2,revision=0 WHERE id=$1',[f.activity,JSON.stringify(current)]);
    await expect(wall.locator('[data-member]')).toHaveCount(0,{timeout:5000});
    await expect(wall.locator('[data-testid="member-wall"]')).toHaveAttribute('data-status','ready');
    checks.push('new activity epoch with lower revision is accepted; prior consent no longer displays');
    assert.deepEqual(errors,[]);writeFileSync('docs/verification/member-wall/browser.json',JSON.stringify({checks,errors},null,2));console.log(JSON.stringify({checks,errors}));
  } finally {await browser.close();await db.end();}
}
void main().catch(e=>{console.error(e);process.exitCode=1});
